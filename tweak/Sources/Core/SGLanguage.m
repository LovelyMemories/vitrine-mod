NSString *SGLocalized(NSString *text) {
    if (!text.length || SGLanguage() != 1) return text;
    // A cell's labels ask for the same literals on every reuse, and every other label of the app asks once: a
    // pointer hit answers without hashing anything, and a miss is kept so the next reuse is one too. Main thread
    // only, where labels are set; another thread goes to the table instead of touching the slots.
    static NSString *cacheKeys[128], *cacheValues[128];
    static BOOL cacheFilled[128];
    BOOL cache = NSThread.isMainThread;
    NSUInteger slot = ((NSUInteger)text >> 4) & 127;
    if (cache && cacheFilled[slot] && cacheKeys[slot] == text) return cacheValues[slot];
    NSDictionary *byText = table();
    NSString *translated = byText[text];
    if (!translated.length) {
        // A section header draws its title in capitals while the table keeps it in sentence case: the table's
        // keys are kept in capitals once, and the text is asked for as it is, rather than lowercasing every
        // label that misses.
        static NSDictionary *byUppercase;
        static dispatch_once_t once;
        dispatch_once(&once, ^{
            NSMutableDictionary *map = [NSMutableDictionary dictionary];
            for (NSString *key in byText) {
                NSString *upper = key.uppercaseString;
                if (!upper.length || map[upper]) continue;
                map[upper] = byText[key];
            }
            byUppercase = [map copy];
        });
        translated = byUppercase[text];
    }
    NSString *answer = translated.length ? translated : text;
    if (cache) {
        cacheKeys[slot] = text;
        cacheValues[slot] = answer;
        cacheFilled[slot] = YES;
    }
    return answer;
}
