// The mod's own wording in the person's language. Only the mod's screens are turned: PlanText.x asks this
// from a label only when the label sits in one of the mod's own view controllers, so Spotify's screens, and
// the app's own language, are never touched. A string not in the table stays as it is, which is how a line
// added later shows in English until its translation lands here.
#import "Core/SGCore.h"
#import "Core/SGLanguage.h"

static NSInteger sg_language = -1;

// The choice is stored by a row (App/ModSettings.x), not through SGLanguageChanged: the defaults' own change
// notification is the one signal every writer goes through. Posted on whichever thread wrote it, so it only
// clears the number here (AGENTS.md).
static void watchLanguage(void) {
    static dispatch_once_t once;
    dispatch_once(&once, ^{
        [NSNotificationCenter.defaultCenter addObserverForName:NSUserDefaultsDidChangeNotification object:nil queue:nil
                                                    usingBlock:^(NSNotification *note) {
            sg_language = -1;
        }];
    });
}

NSInteger SGLanguage(void) {
    watchLanguage();
    // Russian is cached once seen. English is read again for the first two seconds only, while the stored choice
    // may still be on its way in (the first labels of a launch), and then kept until the defaults change: a
    // defaults read for every label the app sets, Spotify's own screens included, is what reading English every
    // time cost while scrolling.
    static CFAbsoluteTime firstRead;
    if (!firstRead) firstRead = CFAbsoluteTimeGetCurrent();
    if (sg_language == 1) return 1;
    if (sg_language == 0 && CFAbsoluteTimeGetCurrent() - firstRead > 2) return 0;
    sg_language = [NSUserDefaults.standardUserDefaults integerForKey:SGKeyLanguage] == 1 ? 1 : 0;
    return sg_language;
}

void SGLanguageChanged(void) {
    sg_language = -1;
}

